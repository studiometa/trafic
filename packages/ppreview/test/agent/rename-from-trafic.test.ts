import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  LEGACY_MIGRATIONS_STATE_FILE,
  migration0024RenameFromTrafic,
  runRenameFromTraficMigration,
} from "../../src/agent/setup/migrations/0024__rename_from_trafic.js";
import { loadMigrationState } from "../../src/agent/setup/migrations/index.js";
import { AGENT_UNIT } from "../../src/agent/setup/agent.js";
import { ROUTER_COMPOSE_OVERRIDE, STATIC_CONFIG, TRAEFIK_DIR } from "../../src/agent/setup/ddev.js";
import { DOCKER_FIREWALL_SCRIPT, DOCKER_FIREWALL_UNIT } from "../../src/agent/setup/docker-firewall.js";
import { SSHD_DROPIN, UNATTENDED_UPGRADES_CONFIG } from "../../src/agent/setup/hardening.js";
import type { TlsConfig } from "../../src/agent/types.js";
import { createFakeIo } from "./helpers/fake-io.js";

const noTls = (): TlsConfig => ({ dnsEnv: {} });

const CONFIG = "/etc/ppreview/config.toml";
const LEGACY_AGENT_UNIT = "/etc/systemd/system/trafic-agent.service";
const LEGACY_FIREWALL_UNIT = "/etc/systemd/system/trafic-docker-firewall.service";
const LEGACY_STATIC_CONFIG = `${TRAEFIK_DIR}/static_config.trafic.yaml`;
const LEGACY_DYNAMIC_CONFIG = `${TRAEFIK_DIR}/custom-global-config/trafic.yaml`;
const LEGACY_OVERRIDE = "/home/ddev/.ddev/router-compose.trafic.yaml";
const RUNNING = JSON.stringify({ raw: [{ name: "my-app", status: "running" }] });

/**
 * A server on @studiometa/trafic-agent 0.1.64. The fake io does not move
 * files on `mv`, so the config is also given at its new path, as the
 * migration reads it after the move.
 */
function legacyServer(extra: Record<string, string> = {}) {
  return createFakeIo({
    files: {
      "/etc/trafic": "",
      "/var/lib/trafic": "",
      "/var/backups/trafic": "",
      [LEGACY_AGENT_UNIT]: "[Unit]\n",
      [CONFIG]: [
        "# Trafic agent configuration",
        "# Generated by trafic setup",
        'db_path = "/var/lib/trafic/db.sqlite"',
        'basic_auth = ["admin:trafic-secret"]',
        "[backup]",
        'dir = "/var/backups/trafic"',
        "",
      ].join("\n"),
      [LEGACY_STATIC_CONFIG]: "entryPoints:\n",
      [LEGACY_DYNAMIC_CONFIG]: "http:\n",
      [LEGACY_OVERRIDE]: "services:\n",
      [LEGACY_FIREWALL_UNIT]: "[Unit]\n",
      "/etc/ssh/sshd_config.d/trafic.conf": "# Trafic SSH hardening\n# Generated by trafic setup\nPermitRootLogin no\n",
      [UNATTENDED_UPGRADES_CONFIG]: "// Trafic: Automatic security updates\n// by `trafic-agent upgrade` instead,\n",
      ...extra,
    },
    output: {
      "ddev list -j": RUNNING,
      "label=com.docker.compose.service=ddev-router": "abc123\n",
      "which ppreview": "/usr/bin/ppreview\n",
    },
  });
}

describe("migration 0024: rename from Trafic", () => {
  it("has a stable id", () => {
    expect(migration0024RenameFromTrafic.id).toBe("0024__rename_from_trafic");
  });

  it("stops the old service before it moves the database", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    const stop = io.commands.indexOf("systemctl disable --now trafic-agent");
    const move = io.commands.indexOf("mv /var/lib/trafic /var/lib/ppreview");

    expect(stop).toBeGreaterThanOrEqual(0);
    expect(move).toBeGreaterThan(stop);
    expect(io.ran(`rm -f ${LEGACY_AGENT_UNIT}`)).toBe(true);
  });

  it("moves the config, database and backup directories", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    expect(io.commands).toContain("mv /etc/trafic /etc/ppreview");
    expect(io.commands).toContain("mv /var/lib/trafic /var/lib/ppreview");
    expect(io.commands).toContain("mv /var/backups/trafic /var/backups/ppreview");
  });

  it("points the config at the new paths, and keeps the values", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    expect(io.written(CONFIG)).toBe(
      [
        "# ppreview agent configuration",
        "# Generated by ppreview setup",
        'db_path = "/var/lib/ppreview/db.sqlite"',
        'basic_auth = ["admin:trafic-secret"]',
        "[backup]",
        'dir = "/var/backups/ppreview"',
        "",
      ].join("\n"),
    );
  });

  it("installs the ppreview-agent service", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    expect(io.written(AGENT_UNIT)).toContain(
      "ExecStart=/usr/bin/ppreview agent start --config /etc/ppreview/config.toml",
    );
    expect(io.commands).toContain("systemctl enable ppreview-agent");
  });

  it("writes the Traefik files with the new names and removes the old ones", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    expect(io.written(STATIC_CONFIG)).toContain("- ppreview-auth@file");
    expect(io.written(`${TRAEFIK_DIR}/custom-global-config/ppreview.yaml`)).toContain(
      "ppreview-catchall:",
    );
    expect(io.written(ROUTER_COMPOSE_OVERRIDE)).toContain("restart: unless-stopped");
    expect(io.commands).toContain(
      `rm -f ${LEGACY_STATIC_CONFIG} ${LEGACY_DYNAMIC_CONFIG} ${LEGACY_OVERRIDE}`,
    );
  });

  it("recreates the router after the old Traefik files are gone", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    const remove = io.commands.findIndex((c) => c.startsWith(`rm -f ${LEGACY_STATIC_CONFIG}`));
    const routerRemoved = io.commands.indexOf("docker rm -f abc123");
    const start = io.commands.findIndex((c) => c.includes("ddev start my-app"));

    expect(routerRemoved).toBeGreaterThan(remove);
    expect(start).toBeGreaterThan(routerRemoved);
  });

  it("does not start a project when none runs", () => {
    const io = legacyServer();
    (io.execSilent as unknown as { mockImplementation: (f: (c: string) => string) => void })
      .mockImplementation((command: string) => {
        io.commands.push(command);
        return "";
      });

    runRenameFromTraficMigration(io, noTls);

    expect(io.ran("ddev start")).toBe(false);
  });

  it("installs the new Docker firewall before it removes the old chain", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    expect(io.written(DOCKER_FIREWALL_SCRIPT)).toContain('CHAIN="PPREVIEW-DOCKER-USER"');
    expect(io.written(DOCKER_FIREWALL_UNIT)).toContain(`ExecStart=${DOCKER_FIREWALL_SCRIPT}`);

    const apply = io.commands.indexOf("systemctl restart ppreview-docker-firewall.service");
    const removeChain = io.commands.findIndex((c) => c.includes("iptables -X TRAFIC-DOCKER-USER"));

    expect(apply).toBeGreaterThanOrEqual(0);
    expect(removeChain).toBeGreaterThan(apply);
    expect(io.ran("ip6tables -X TRAFIC-DOCKER-USER")).toBe(true);
    expect(io.ran(`rm -f ${LEGACY_FIREWALL_UNIT} /usr/local/sbin/trafic-docker-firewall`)).toBe(true);
  });

  it("renames the files setup wrote and the old name in them", () => {
    const io = legacyServer();

    runRenameFromTraficMigration(io, noTls);

    expect(io.commands).toContain(`mv /etc/ssh/sshd_config.d/trafic.conf ${SSHD_DROPIN}`);
    expect(io.written(UNATTENDED_UPGRADES_CONFIG)).toBe(
      "// ppreview: Automatic security updates\n// by `ppreview-agent upgrade` instead,\n",
    );
  });

  it("removes an old file when the new one already exists", () => {
    const io = legacyServer({ [SSHD_DROPIN]: "# ppreview SSH hardening\n" });

    runRenameFromTraficMigration(io, noTls);

    expect(io.commands).toContain("rm -f /etc/ssh/sshd_config.d/trafic.conf");
  });

  it("stops when an old directory and its new one both exist", () => {
    const io = legacyServer({ "/var/lib/ppreview": "" });

    expect(() => runRenameFromTraficMigration(io, noTls)).toThrow(
      "/var/lib/trafic and /var/lib/ppreview both exist",
    );
  });

  it("does nothing on a server that has the new names", () => {
    const io = createFakeIo({
      files: { [CONFIG]: 'db_path = "/var/lib/ppreview/db.sqlite"\n', [AGENT_UNIT]: "[Unit]\n" },
    });

    runRenameFromTraficMigration(io, noTls);

    expect(io.commands).toEqual([]);
    expect(io.writes.size).toBe(0);
  });
});

describe("loadMigrationState", () => {
  let dir: string;

  beforeEach(() => {
    dir = join(tmpdir(), `ppreview-state-${Date.now()}-${Math.random().toString(36).slice(2)}`);
    mkdirSync(dir, { recursive: true });
  });

  afterEach(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  it("keeps the old state file at its path until 0024 moves it", () => {
    expect(LEGACY_MIGRATIONS_STATE_FILE).toBe("/etc/trafic/.migrations.json");
  });

  it("reads the given state file", () => {
    const file = join(dir, ".migrations.json");
    writeFileSync(file, JSON.stringify({ applied: ["0001__ddev_apt_repo"] }));

    expect(loadMigrationState(file)).toEqual({ applied: ["0001__ddev_apt_repo"] });
  });

  it("returns an empty state when the file does not exist", () => {
    expect(loadMigrationState(join(dir, "missing.json"))).toEqual({ applied: [] });
  });
});
